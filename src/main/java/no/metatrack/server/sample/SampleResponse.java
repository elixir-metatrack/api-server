package no.metatrack.server.sample;

import org.eclipse.microprofile.openapi.annotations.media.Schema;

import java.time.Instant;
import java.time.LocalDate;
import java.util.Map;
import java.util.UUID;

@Schema(description = "Sample details, including active custom metadata values. Fields with no stored value are null.")
public record SampleResponse(
        UUID id,
        String name,
        String alias,
        Integer taxId,
        Integer hostTaxId,
        String mlst,
        String isolationSource,
        LocalDate collectionDate,
        String location,
        String sequencingLab,
        String institution,
        String hostHealthState,
        String projectTitle,
        String description,
        String isolate,
        String collectedBy,
        Double latitude,
        Double longitude,
        String environmentalSample,
        String hostAssociated,
        String hostCommonName,
        String hostSubjectId,
        String collectorName,
        String collectingInstitution,
        String hostSex,
        String influenzaTestMethod,
        String influenzaTestResult,
        String otherPathogensTested,
        String otherPathogensTestResult,
        String hostHabitat,
        String isolationSourceHostAssociated,
        String hostBehaviour,
        String isolationSourceNonHostAssociated,
        String influenzaVirusType,
        String influenzaSubType,
        String serovar,
        String strain,
        String hostAge,
        String county,
        String commune,
        String hospitalHealthInstitution,
        Instant createdOn,
        Instant modifiedOn,
        String projectAccession,
        String studyAccession,
        String sampleAccession,
        String secondaryAccession,
        @Schema(description = "Active custom metadata values keyed by metadata-field key")
        Map<String, Object> customMetadata) {
    public static SampleResponse fromEntity(Sample sample, Map<String, Object> customMetadata) {
        return new SampleResponse(
                sample.id,
                sample.name,
                sample.alias,
                sample.taxId,
                sample.hostTaxId,
                sample.mlst,
                sample.isolationSource,
                sample.collectionDate,
                sample.location,
                sample.sequencingLab,
                sample.institution,
                sample.hostHealthState,
                sample.projectTitle,
                sample.description,
                sample.isolate,
                sample.collectedBy,
                sample.latitude,
                sample.longitude,
                sample.environmentalSample,
                sample.hostAssociated,
                sample.hostCommonName,
                sample.hostSubjectId,
                sample.collectorName,
                sample.collectingInstitution,
                sample.hostSex,
                sample.influenzaTestMethod,
                sample.influenzaTestResult,
                sample.otherPathogensTested,
                sample.otherPathogensTestResult,
                sample.hostHabitat,
                sample.isolationSourceHostAssociated,
                sample.hostBehaviour,
                sample.isolationSourceNonHostAssociated,
                sample.influenzaVirusType,
                sample.influenzaSubType,
                sample.serovar,
                sample.strain,
                sample.hostAge,
                sample.county,
                sample.commune,
                sample.hospitalHealthInstitution,
                sample.createdOn,
                sample.modifiedOn,
                sample.projectAccession,
                sample.studyAccession,
                sample.sampleAccession,
                sample.secondaryAccession,
                customMetadata);
    }
}
